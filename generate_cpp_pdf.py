# Helper function to wrap code lines to fit the page margin
def wrap_code_lines(code, max_len=80):
    wrapped_lines = []
    for line in code.splitlines():
        # Clean trailing spaces
        line = line.rstrip()
        if len(line) > max_len:
            # Preserve leading indentation
            indent = len(line) - len(line.lstrip())
            indent_str = ' ' * indent
            chunk_size = max_len - indent
            if chunk_size <= 15:
                # If indentation is too deep, don't indent wrapped parts as much
                indent_str = '    '
                chunk_size = max_len - 4
            
            first_chunk = line[:max_len]
            wrapped_lines.append(first_chunk)
            
            rem = line[max_len:]
            while rem:
                chunk = indent_str + rem[:chunk_size]
                wrapped_lines.append(chunk)
                rem = rem[chunk_size:]
        else:
            wrapped_lines.append(line)
    return '\n'.join(wrapped_lines)

# Two-pass canvas to dynamically compute "Page X of Y" and add headers/footers
class NumberedCanvas(canvas.Canvas):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        # We don't draw running headers/footers on the title page (page 1)
        if self._pageNumber == 1:
            return
            
        self.saveState()
        self.setFont("Helvetica-Bold", 8)
        self.setFillColor(colors.HexColor('#475569')) # Slate 600
        
        # Running Header
        self.drawString(54, 750, "STRIVER A2Z DSA SHEET - C++ SOLUTIONS CATALOG")
        self.setFont("Helvetica", 8)
        self.drawRightString(558, 750, "C++ ONLY")
        self.setStrokeColor(colors.HexColor('#CBD5E1')) # Slate 300
        self.setLineWidth(0.5)
        self.line(54, 742, 558, 742)
        
        # Running Footer
        self.setFont("Helvetica", 8)
        self.drawString(54, 40, "Generated by DSA Scraper Bot")
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(558, 40, page_text)
        self.line(54, 52, 558, 52)
        self.restoreState()

def build_pdf(json_path, pdf_path):
    print(f"Loading database from {json_path}...")
    with open(json_path, 'r', encoding='utf-8') as f:
        db = json.load(f)
        
    print("Initializing styles...")
    styles = getSampleStyleSheet()
    
    # Custom styles
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=24,
        leading=30,
        alignment=TA_CENTER,
        textColor=colors.HexColor('#0F172A'), # Slate 900
        spaceAfter=15
    )
    
    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=12,
        leading=16,
        alignment=TA_CENTER,
        textColor=colors.HexColor('#475569'), # Slate 600
        spaceAfter=40
    )
    
    cat_style = ParagraphStyle(
        'CategoryHeading',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=16,
        leading=20,
        textColor=colors.HexColor('#0F172A'),
        spaceBefore=22,
        spaceAfter=10,
        keepWithNext=True
    )
    
    subcat_style = ParagraphStyle(
        'SubcategoryHeading',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=12,
        leading=16,
        textColor=colors.HexColor('#2563EB'), # Blue 600
        spaceBefore=16,
        spaceAfter=8,
        keepWithNext=True
    )
    
    prob_style = ParagraphStyle(
        'ProblemHeading',
        parent=styles['Heading3'],
        fontName='Helvetica-Bold',
        fontSize=10,
        leading=13,
        textColor=colors.HexColor('#1E293B'), # Slate 800
        spaceBefore=10,
        spaceAfter=4,
        keepWithNext=True
    )
    
    approach_style = ParagraphStyle(
        'ApproachHeading',
        parent=styles['Normal'],
        fontName='Helvetica-BoldOblique',
        fontSize=9,
        leading=11,
        textColor=colors.HexColor('#059669'), # Emerald 600
        spaceBefore=6,
        spaceAfter=2,
        keepWithNext=True
    )

    code_font_style = ParagraphStyle(
        'CodeFontStyle',
        fontName='Courier',
        fontSize=7.5,
        leading=9,
        textColor=colors.HexColor('#0F172A'),
        backColor=colors.HexColor('#F8FAFC'),
        borderColor=colors.HexColor('#E2E8F0'),
        borderWidth=0.5,
        borderPadding=6,
        spaceBefore=4,
        spaceAfter=6
    )
    
    desc_style = ParagraphStyle(
        'DescStyle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor('#334155'), # Slate 700
        spaceAfter=6
    )

    story = []
    
    # 1. Title Page elements
    story.append(Spacer(1, 150))
    story.append(Paragraph("STRIVER A2Z DSA SHEET", title_style))
    story.append(Paragraph("Complete C++ Solutions Catalog", ParagraphStyle('SubTitleBold', parent=title_style, fontSize=16, leading=20, spaceAfter=8, textColor=colors.HexColor('#2563EB'))))
    story.append(Paragraph("Compiled and Formatted into a Single Reference Manual", subtitle_style))
    story.append(Spacer(1, 100))
    
    meta_style = ParagraphStyle('Meta', parent=styles['Normal'], fontName='Helvetica', fontSize=9, leading=14, alignment=TA_CENTER, textColor=colors.HexColor('#64748B'))
    story.append(Paragraph("Source: takeuforward.org", meta_style))
    story.append(Paragraph("Skip Language: Java / Python / JavaScript", meta_style))
    story.append(Paragraph("Format: C++ Source Code Only", meta_style))
    story.append(PageBreak())
    
    # 2. Iterate and build the document
    category_count = 0
    problem_count = 0
    cpp_files_found = 0
    
    for category in db:
        category_added = False
        
        for subcategory in category["subcategories"]:
            subcategory_added = False
            
            for problem in subcategory["problems"]:
                if not problem.get("scraped") or not problem.get("solutions"):
                    continue
                
                # Check if there is C++ code in any approach of this problem
                has_cpp = False
                cpp_solutions = {}
                for approach_name, approach_details in problem["solutions"].items():
                    if not isinstance(approach_details, dict) or "code" not in approach_details:
                        continue
                    # Check for C++ or C or CPP keys
                    code_dict = approach_details["code"]
                    cpp_key = None
                    for key in code_dict.keys():
                        if key.lower() in ["cpp", "c++", "c"]:
                            cpp_key = key
                            break
                    if cpp_key and code_dict[cpp_key].strip():
                        has_cpp = True
                        cpp_solutions[approach_name] = {
                            "description": approach_details.get("description", ""),
                            "code": code_dict[cpp_key].strip(),
                            "complexity": approach_details.get("complexity", "")
                        }
                
                if not has_cpp:
                    continue
                
                # Add Category if not already added in this layout
                if not category_added:
                    story.append(Paragraph(f"Category: {category['category_name']}", cat_style))
                    story.append(Spacer(1, 5))
                    category_added = True
                    category_count += 1
                
                # Add Subcategory if not already added
                if not subcategory_added:
                    story.append(Paragraph(f"Subcategory: {subcategory['subcategory_name']}", subcat_style))
                    story.append(Spacer(1, 4))
                    subcategory_added = True
                
                # Add Problem Title
                prob_title = f"{problem['problem_name']} ({problem.get('difficulty', 'Medium')})"
                story.append(Paragraph(prob_title, prob_style))
                problem_count += 1
                
                # Add C++ Solutions for this problem
                for approach_name, details in cpp_solutions.items():
                    # Keep heading + description together so they don't get orphaned
                    head_flowables = [
                        Paragraph(f"Approach: {approach_name}", approach_style)
                    ]
                    
                    clean_desc = details["description"].strip()
                    if clean_desc and clean_desc.lower() != "n/a" and clean_desc.lower() != "none":
                        clean_desc_html = html.escape(clean_desc).replace('\n', '<br/>')
                        head_flowables.append(Paragraph(clean_desc_html, desc_style))
                    
                    story.append(KeepTogether(head_flowables))
                    
                    # Add code block directly as Preformatted (splits across pages safely!)
                    escaped_code = html.escape(details["code"])
                    wrapped_code = wrap_code_lines(escaped_code, max_len=84)
                    pre = Preformatted(wrapped_code, code_font_style)
                    story.append(pre)
                    
                    # Add complexity analysis
                    if details["complexity"]:
                        comp_text = f"<b>Complexity Analysis:</b> {html.escape(details['complexity'])}"
                        story.append(Paragraph(comp_text, desc_style))
                    
                    story.append(Spacer(1, 10))
                    cpp_files_found += 1
                
                story.append(Spacer(1, 12))

    print("Building PDF document...")
    # Letter is 612x792. Margins: left=54, right=54, top=54, bottom=54 (giving printable width 504)
    doc = SimpleDocTemplate(
        pdf_path,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54
    )
    
    doc.build(story, canvasmaker=NumberedCanvas)
    print(f"\nPDF Generation Complete!")
    print(f"Categories Processed: {category_count}")
    print(f"Problems Scraped (C++): {problem_count}")
    print(f"Solutions Written: {cpp_files_found}")
    print(f"Saved PDF to: {pdf_path}")

if __name__ == "__main__":
    json_db = "parsed_sheet.json"
    pdf_out = "striver_cpp_solutions.pdf"
    
    if not os.path.exists(json_db):
        print(f"Error: JSON database '{json_db}' not found in the current directory.")
        sys.exit(1)
        
    build_pdf(json_db, pdf_out)
